import re
import unicodedata
import streamlit as st

st.set_page_config(page_title="Арамейский → русский", layout="centered")
st.title("Арамейский → русский")
st.caption("Бесплатный словарный переводчик. Поддерживает арамейский текст еврейским письмом (таргумы) и сирийским письмом (Пешитта).")
st.info("Пока доступен ограниченный проверяемый подстрочник, а не полноценный литературный перевод. Незнакомые слова не переводятся наугад.")

# A small starter lexicon, not a general-purpose machine translator.
HEBREW_SCRIPT = {
    "בקדמין": ("в начале", "наречное выражение"),
    "ברא": ("сотворил", "глагол, 3-е лицо ед. ч."),
    "יי": ("Господь", "условная запись божественного имени"),
    "ית": ("показатель прямого дополнения", "служебное слово; обычно не переводится отдельно"),
    "שׁמיא": ("небеса", "существительное"),
    "שמיא": ("небеса", "существительное"),
    "וית": ("и + показатель дополнения", "союз и служебное слово"),
    "ארעא": ("земля", "существительное"),
    "וארעא": ("и земля", "союз и существительное"),
    "הות": ("была", "форма глагола «быть»"),
    "צדיא": ("пуста / опустошена", "прилагательное"),
    "וריקניא": ("и пуста", "союз и прилагательное"),
    "וחשוכא": ("и тьма", "союз и существительное"),
    "על": ("на / над", "предлог"),
    "אפי": ("поверхности / лице", "существительное в сочетании с предлогом"),
    "תהומא": ("бездна", "существительное"),
    "ורוחא": ("и дух / ветер", "многозначное существительное"),
    "מן": ("от / из", "предлог"),
    "קדם": ("перед / от лица", "предлог или существительное в конструкции"),
    "מנשבא": ("веяла", "глагольная форма"),
    "מיא": ("воды", "существительное"),
}
SYRIAC = {
    "ܒܪܫܝܬ": ("в начале", "предлог + существительное"),
    "ܐܝܬܘܗܝ": ("был / существовал", "экзистенциальная конструкция"),
    "ܡܠܬܐ": ("слово / речь", "существительное"),
    "ܗܘܐ": ("был / стал", "глагол"),
    "ܐܠܗܐ": ("Бог", "существительное"),
    "ܠܘܬ": ("у / к / с", "предлог"),
    "ܗܘ": ("он / тот", "местоимение"),
    "ܢܘܗܪܐ": ("свет", "существительное"),
    "ܚܝܐ": ("жизнь / живые", "контекст необходим"),
    "ܒܪܐ": ("сотворил", "глагол"),
    "ܝܬ": ("показатель прямого дополнения", "служебное слово"),
    "ܫܡܝܐ": ("небеса", "существительное"),
    "ܘܝܬ": ("и + показатель дополнения", "союз и служебное слово"),
    "ܐܪܥܐ": ("земля", "существительное"),
}

def normalize(token):
    return "".join(ch for ch in token if unicodedata.category(ch) != "Mn" and ch not in "׃.,;:!?()[]{}״׳")

sample = "בְּקַדְמִין בְּרָא יְיָ יָת שְׁמַיָּא וְיָת אַרְעָא"
source = st.text_area("Вставьте арамейский текст", value=sample, height=170)
st.caption("Пример: Таргум Онкелоса, Бытие 1:1. Оригинал остаётся без изменений.")
if st.button("Перевести на русский", type="primary"):
    tokens = source.split()
    if not tokens:
        st.warning("Вставьте текст для перевода.")
    else:
        rows, glosses, missing = [], [], []
        for token in tokens:
            key = normalize(token)
            lex = SYRIAC if any("\\u0700" <= c <= "\\u074f" for c in token) else HEBREW_SCRIPT
            result = lex.get(key)
            if result:
                gloss, note = result
                rows.append({"Слово": token, "Русское значение": gloss, "Примечание": note})
                glosses.append(gloss)
            else:
                rows.append({"Слово": token, "Русское значение": "не установлено", "Примечание": "нет в словаре"})
                glosses.append("[" + token + "]")
                missing.append(token)
        st.subheader("Русский подстрочник")
        st.write(" · ".join(glosses))
        st.subheader("Разбор слов")
        st.dataframe(rows, hide_index=True, use_container_width=True)
        if missing:
            st.warning(f"Неизвестных слов: {len(missing)}. Полный перевод этого фрагмента пока невозможен.")
        else:
            st.caption("Это пословный перевод, а не литературная реконструкция смысла.")
st.caption("Для научного цитирования сверяйте чтения с конкретным изданием или рукописью. Никаких платных API.")
