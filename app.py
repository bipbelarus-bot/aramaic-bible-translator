import streamlit as st
st.set_page_config(page_title='Aramaic Bible → Русский', layout='wide')
st.title('ܦܫܝܛܬܐ · Арамейская Библия → русский')
st.caption('Прямой перевод с сирийского арамейского. Прототип: для автоматического перевода требуется подключение языковой модели и проверенного корпуса Пешитты.')
source=st.text_area('Арамейский оригинал',height=170,placeholder='Вставьте текст на сирийском арамейском')
mode=st.selectbox('Режим', ['Буквальный','Литературный','Филологический анализ'])
if st.button('Подготовить перевод'):
    if not source.strip(): st.warning('Введите арамейский текст.')
    else:
        st.info('Текст принят. Автоматический перевод пока не подключён: прототип не выдумывает перевод.')
        st.code(source)
        st.write('Режим:',mode)
        st.write('Следующий модуль: морфологический разбор и прямой перевод арамейский → русский с указанием неопределённостей.')
